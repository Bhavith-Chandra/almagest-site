"""Fetch real daily closes for the case study chart into assets/market.js.

Run: uv run --project .. --with yfinance python build_market.py
Source: Yahoo Finance via yfinance. ^SOX = PHLX Semiconductor Index, ^GSPC = S&P 500.
"""
import json
from datetime import datetime, timezone
from pathlib import Path

import yfinance as yf

START, END = "2026-04-01", "2026-11-06"  # END is exclusive: last close is 5 Nov 2026
out = {"fetched_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"), "source": "Yahoo Finance via yfinance"}
for key, ticker in [("sox", "^SOX"), ("spx", "^GSPC")]:
    close = yf.download(ticker, start=START, end=END, progress=False, auto_adjust=False)["Close"][ticker].dropna()
    out[key] = [[d.strftime("%Y-%m-%d"), round(float(v), 2)] for d, v in close.items()]
    print(ticker, len(out[key]), out[key][0], out[key][-2:])

path = Path(__file__).parent / "assets" / "market.js"
path.write_text("// generated by site/build_market.py; real daily closes\nwindow.MARKET = " + json.dumps(out) + ";\n")
print("wrote", path)
